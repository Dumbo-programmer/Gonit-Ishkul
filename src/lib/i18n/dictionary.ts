export type TranslationKey = keyof typeof translations;

function resolve(key: string): unknown {
  const parts = key.split(".");
  let node: unknown = translations;
  for (const part of parts) {
    if (node === null || typeof node !== "object") return undefined;
    node = (node as Record<string, unknown>)[part];
  }
  return node;
}

export function t(key: string, lang: Lang): string {
  const node = resolve(key);
  if (node && typeof node === "object" && !Array.isArray(node)) {
    const value = (node as Record<string, unknown>)[lang];
    if (typeof value === "string") return value;
  }
  const parts = key.split(".");
  return parts[parts.length - 1];
}

// Look up a list of bilingual {bn,en} entries by dotted key
export function tList(key: string, lang: Lang): { bn: string; en: string }[] {
  void lang;
  const node = resolve(key);
  if (Array.isArray(node)) {
    return node.filter(
      (item): item is { bn: string; en: string } =>
        !!item &&
        typeof item === "object" &&
        typeof (item as { bn?: unknown }).bn === "string" &&
        typeof (item as { en?: unknown }).en === "string",
    );
  }
  return [];
}