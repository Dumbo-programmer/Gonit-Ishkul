/**
 * Adds arena problems introduced after a store was first provisioned. Safe to
 * run repeatedly: only problems whose id is missing are appended, so an
 * already-seeded production store picks up newly authored problems without
 * duplicating the ones it already has.
 */
function backfillArena(store: StoreShape): boolean {
  const now = new Date().toISOString();
  const scratch = emptyStore();
  seedArena(scratch, now);
  const existing = new Set(store.problems.map((p) => p.id));
  let changed = false;
  for (const problem of scratch.problems) {
    if (!existing.has(problem.id)) {
      store.problems.push(problem);
      changed = true;
    }
  }
  return changed;
}

